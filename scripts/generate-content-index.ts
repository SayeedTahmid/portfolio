/**
 * Discovers content that can be added or removed just by adding or deleting files:
 *
 *   content/projects/<slug>/project.ts   one folder per project (folders starting
 *                                        with "_" are ignored, e.g. _template)
 *   content/profile-photo.{jpg,jpeg,png,webp,avif}   optional profile photo
 *
 * and writes two small modules the site imports:
 *
 *   content/projects/index.generated.ts
 *   content/profile-photo.generated.ts
 *
 * Runs automatically before `npm install` finishes, `npm run dev`, `npm run build`,
 * `npm run typecheck`, `npm run lint` and the content checks, so it never needs to
 * be run by hand. Both outputs are git-ignored.
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const contentDir = join(root, "content");
const projectsDir = join(contentDir, "projects");
const banner = [
  "// Generated by scripts/generate-content-index.ts. Do not edit; changes are overwritten.",
  "// Add or remove content by adding or deleting files (see docs/MANAGING-CONTENT.md).",
];

/** Writes only when the content changed, so the dev server doesn't reload needlessly. */
function writeIfChanged(path: string, content: string): void {
  if (existsSync(path) && readFileSync(path, "utf8") === content) return;
  writeFileSync(path, content);
}

// Projects -----------------------------------------------------------------
const folders = existsSync(projectsDir)
  ? readdirSync(projectsDir, { withFileTypes: true })
      .filter(
        (entry) =>
          entry.isDirectory() &&
          !entry.name.startsWith("_") &&
          !entry.name.startsWith("."),
      )
      .map((entry) => entry.name)
      .sort()
  : [];

const withoutFile = folders.filter(
  (folder) => !existsSync(join(projectsDir, folder, "project.ts")),
);
if (withoutFile.length > 0) {
  console.error(
    `content/projects: these folders have no project.ts: ${withoutFile.join(", ")}.\n` +
      "Add a project.ts (copy content/projects/_template/project.ts) or delete the folder.",
  );
  process.exit(1);
}

const projectIndex = [
  ...banner,
  'import type { Project } from "../types.ts";',
  ...folders.map(
    (folder, i) => `import project${i} from "./${folder}/project.ts";`,
  ),
  "",
  `export const projectFolders: readonly string[] = ${JSON.stringify(folders)};`,
  `export const projectModules: readonly Project[] = [${folders
    .map((_, i) => `project${i}`)
    .join(", ")}];`,
  "",
].join("\n");
writeIfChanged(join(projectsDir, "index.generated.ts"), projectIndex);

// Profile photo -------------------------------------------------------------
const photoNames = ["jpg", "jpeg", "png", "webp", "avif"]
  .map((ext) => `profile-photo.${ext}`)
  .filter((name) => existsSync(join(contentDir, name)));
if (photoNames.length > 1) {
  console.error(
    `content/: found more than one profile photo (${photoNames.join(", ")}). Keep one.`,
  );
  process.exit(1);
}
const photo = photoNames[0];
const photoModule = [
  ...banner,
  'import type { StaticImageData } from "next/image";',
  ...(photo ? [`import photo from "./${photo}";`] : []),
  "",
  `export const profilePhoto: StaticImageData | null = ${photo ? "photo" : "null"};`,
  "",
].join("\n");
writeIfChanged(join(contentDir, "profile-photo.generated.ts"), photoModule);

console.log(
  `content index: ${folders.length} project(s); profile photo: ${photo ?? "none"}`,
);
